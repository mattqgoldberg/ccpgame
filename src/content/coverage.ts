import type { TaskId } from './exam';

/**
 * How an exam topic shows up in play.
 * - architecture: a node in the build canvas, with real stats in the simulation
 * - incident:     the answer to an attack, outage, or audit event
 * - business:     part of the economy (bill, pricing commitments, support plan, staff, accounts)
 * - request:      fulfils a CEO / customer feature request
 * - prologue:     taught by the on-premises opening chapter
 * - report-card:  graded in the end-of-level Well-Architected review
 * - skill-tree:   a company upgrade between levels
 * - board:        appears in optional board-meeting questions
 * - codex:        has a Codex card (every entry gets one implicitly)
 */
export type Mechanic =
  | 'architecture'
  | 'incident'
  | 'business'
  | 'request'
  | 'prologue'
  | 'report-card'
  | 'skill-tree'
  | 'board'
  | 'codex';

/**
 * 1 = simulated: real stats in the engine.
 * 2 = event/decision: picked to resolve an incident or request; simple effect.
 * 3 = recognition only: Codex card + board questions.
 */
export type Tier = 1 | 2 | 3;

export interface CoverageEntry {
  id: string;
  name: string;
  kind: 'service' | 'concept';
  task: TaskId;
  tier: Tier;
  /** Chapter that first introduces it. */
  chapter: number;
  mechanics: Mechanic[];
  /** How the player meets it in the game. */
  hook: string;
  /** Phrases in exam questions that point to this answer. */
  triggers: string[];
}

